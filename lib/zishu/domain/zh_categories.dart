final Map<String, String> _cidToZh = <String, String>{};

/// 分类号统一 key:去前导零(web `cateNoKey` 同构)——categoryList 的
/// category_no 与 player_live_api 的 CATE 都是带前导零形式,房间列表的
/// broad_cate_no 则无前导零,归一后三种来源才可互查。
String soopCateNoKey(String raw) => raw.trim().replaceFirst(RegExp(r'^0+(?=\d)'), '');

/// 分类树(zh_CN)解析时记录一条 cid→中文名。
void rememberSoopZhCategory(String cid, String zhName) {
  final key = soopCateNoKey(cid);
  if (key.isEmpty || zhName.isEmpty) return;
  _cidToZh[key] = zhName;
}

/// 房间列表/详情按 category_no 反查中文名:进程表(解析层预热填充)优先,
/// 静态 cid 表兜底;仍未命中返回 null(调用方回退原名 + remap 归一,与 web
/// 原名回退一致)。
String? soopZhCategoryName(String cid) {
  final key = soopCateNoKey(cid);
  if (key.isEmpty) return null;
  return _cidToZh[key] ?? _kStaticCidZh[key];
}

/// 按韩文原生名反查静态中文表;供无分类号的名称路径(收藏快照/我的分类
/// 面板只存平台原生名)与名称匹配桥接使用。未命中返回 null。
String? soopZhNameFromNative(String? nativeName) {
  final key = (nativeName ?? '').trim();
  if (key.isEmpty) return null;
  return _kStaticNativeZh[key];
}
